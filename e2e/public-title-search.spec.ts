import { expect, test } from '@playwright/test';

test('market search returns actual title matches, not description matches, and clears back to the feed', async ({ page, request }, info) => {
  const titleQuery = `TitleSearch-${info.project.name}`;
  const descriptionQuery = `DescriptionOnly-${info.project.name}`;
  const expectedId = `e2e-title-search-${info.project.name}`;
  const titleResult = await request.get(`/api/marketplace/listings?q=${titleQuery}`);
  expect(titleResult.ok()).toBe(true);
  const titlePayload = await titleResult.json();
  expect(titlePayload.listings.map((listing: { id: string }) => listing.id)).toEqual([expectedId]);
  expect(titlePayload.listings.every((listing: { title: string }) => listing.title === titleQuery)).toBe(true);
  const descriptionResult = await request.get(`/api/marketplace/listings?q=${descriptionQuery}`);
  expect(descriptionResult.ok()).toBe(true);
  expect((await descriptionResult.json()).listings).toEqual([]);
  const categoryResult = await request.get(`/api/marketplace/listings?q=${titleQuery}&category=other&minPrice=100&maxPrice=100&city=` + encodeURIComponent('الرياض'));
  expect(categoryResult.ok()).toBe(true);
  expect((await categoryResult.json()).listings.map((listing: { id: string }) => listing.id)).toEqual([expectedId]);
  const wrongCategory = await request.get(`/api/marketplace/listings?q=${titleQuery}&category=cameras`);
  expect(wrongCategory.ok()).toBe(true);
  expect((await wrongCategory.json()).listings).toEqual([]);
  const wrongPrice = await request.get(`/api/marketplace/listings?q=${titleQuery}&minPrice=101`);
  expect(wrongPrice.ok()).toBe(true);
  expect((await wrongPrice.json()).listings).toEqual([]);
  const tooCheap = await request.get(`/api/marketplace/listings?q=${titleQuery}&maxPrice=99`);
  expect(tooCheap.ok()).toBe(true);
  expect((await tooCheap.json()).listings).toEqual([]);
  await page.goto('/');
  const search = page.getByPlaceholder('ابحث في كل السوق');
  const searched = page.waitForResponse(response => response.url().includes('/api/marketplace/listings?') && new URL(response.url()).searchParams.get('q') === titleQuery);
  await search.fill(titleQuery);
  expect((await searched).ok()).toBe(true);
  await expect(page.locator('.marketplace-listing-card')).toHaveCount(1);
  await expect(page.locator('.marketplace-listing-card').first()).toContainText(titleQuery);
  const empty = page.waitForResponse(response => response.url().includes('/api/marketplace/listings?') && new URL(response.url()).searchParams.get('q') === descriptionQuery);
  await search.fill(descriptionQuery);
  expect((await empty).ok()).toBe(true);
  await expect(page.locator('.marketplace-listing-card')).toHaveCount(0);
  const cleared = page.waitForResponse(response => response.url().includes('/api/marketplace/listings?') && !new URL(response.url()).searchParams.has('q'));
  await page.getByRole('button', { name: 'مسح البحث', exact: true }).click();
  await cleared;
  await expect(search).toHaveValue('');
  await expect(page.locator('.marketplace-listing-card').first()).toBeVisible();
});
